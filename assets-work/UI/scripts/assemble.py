#!/usr/bin/env python3
"""Assemble the five fixed-size HUD atlases from retained imagegen artwork.

Requires Pillow and numpy. Writes only assets-work/UI. Installation is a separate
validated step. Generated paintings are inputs, never regenerated by this script.
"""

from __future__ import annotations

import io
import json
import subprocess
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

import numpy as np
from PIL import Image, ImageEnhance

ROOT = Path(__file__).resolve().parents[3]
WORK = ROOT / "assets-work/UI"
SOURCE = WORK / "source"
ORIGINAL = WORK / "original/Interface/partCharge1"
MASTERS = WORK / "masters/Interface/partCharge1"
PAYLOADS = WORK / "payloads/Interface/partCharge1"
EXPORTS = WORK / "exports/Interface/partCharge1"
LAYOUT = json.loads((SOURCE / "layout.json").read_text())
CELL_WIDTH, CELL_HEIGHT = LAYOUT["buttons"]["cell"]
# Use the same geometry for all states: hue/light changes never shift the icon.
STATE_BRIGHTNESS = (1.0, 1.15, 0.68, 1.03)
STATE_WARMTH = ((1.0, 1.0, 1.0), (1.09, 1.03, 0.88),
                (1.0, 1.0, 1.0), (1.12, 1.04, 0.88))
SOURCE_COLOR_STRENGTH = 0.9
SELECTED_ICON_BRIGHTNESS = 0.9
SELECTED_RULE = (148, 119, 58)
SELECTED_HOVER_RULE = (208, 172, 88)
SELECTED_RULE_Y = 38
SELECTED_RULE_X = (5, 25)
JPEG_QUALITY = 100


def load_painting(path):
    """Working paintings may contain alpha; the original OZJ contract is opaque."""
    image = Image.open(path).convert("RGBA")
    black = Image.new("RGBA", image.size, (0, 0, 0, 255))
    return Image.alpha_composite(black, image).convert("RGB")


def png_bytes(image):
    output = io.BytesIO()
    image.save(output, format="PNG")
    return output.getvalue()


def write_ora(path, base, overlay, merged):
    """Two native-size editable layers; transparent overlay includes the mask."""
    document = ET.Element("image", w=str(base.width), h=str(base.height), version="0.0.3")
    stack = ET.SubElement(document, "stack")
    for name, source in (("Painted replacement (protected areas masked)", "data/paint.png"),
                         ("Untouched original - alignment reference", "data/original.png")):
        ET.SubElement(stack, "layer", name=name, src=source, x="0", y="0", opacity="1.0",
                      visibility="visible", **{"composite-op": "svg:src-over"})
    with zipfile.ZipFile(path, "w") as archive:
        archive.writestr("mimetype", "image/openraster", compress_type=zipfile.ZIP_STORED)
        archive.writestr("stack.xml", ET.tostring(document))
        archive.writestr("data/original.png", png_bytes(base.convert("RGBA")))
        archive.writestr("data/paint.png", png_bytes(overlay))
        archive.writestr("mergedimage.png", png_bytes(merged))
        thumb = merged.copy()
        thumb.thumbnail((256, 256))
        archive.writestr("Thumbnails/thumbnail.png", png_bytes(thumb))


def save_asset(stem, original, painting, mask):
    merged = Image.composite(painting, original, mask).convert("RGB")
    overlay = painting.convert("RGBA")
    overlay.putalpha(mask)
    for directory in (MASTERS, PAYLOADS, EXPORTS, SOURCE / "editable", SOURCE / "masks"):
        directory.mkdir(parents=True, exist_ok=True)
    merged.save(MASTERS / f"{stem}.png")
    mask.save(SOURCE / "masks" / f"{stem}.png")
    write_ora(SOURCE / "editable" / f"{stem}.ora", original, overlay, merged)
    payload = PAYLOADS / f"{stem}.jpg"
    merged.save(payload, quality=JPEG_QUALITY, subsampling=0, optimize=False, progressive=False)
    subprocess.run([sys.executable, str(ROOT / "tools/mu_texture.py"), "wrap", str(payload),
                    "--out", str(EXPORTS / f"{stem}.OZJ")], check=True)


def assemble_panel():
    original = Image.open(ORIGINAL / "newui_menu03.jpg").convert("RGB")
    generated = load_painting(SOURCE / "panel-generated.png")
    # The square generation canvas is an editing aid; only this band is sampled.
    generated = generated.resize((1024, 1024), Image.Resampling.LANCZOS)
    crop = LAYOUT["panel"]["generation_crop_normalized_1024"]
    painting = generated.crop(crop).resize(original.size, Image.Resampling.LANCZOS)
    painting = ImageEnhance.Color(painting).enhance(SOURCE_COLOR_STRENGTH)
    mask = np.full((original.height, original.width), 255, dtype=np.uint8)
    for x0, y0, x1, y1 in LAYOUT["panel"]["protected_rectangles_xyxy"]:
        mask[y0:y1, x0:x1] = 0
    save_asset("newui_menu03", original, painting, Image.fromarray(mask))


def button_state(normal, state, glyph_box):
    pixels = np.asarray(normal, dtype=np.float32)
    pixels *= STATE_BRIGHTNESS[state]
    pixels *= np.asarray(STATE_WARMTH[state], dtype=np.float32)
    if state == 2:
        x0, y0, x1, y1 = glyph_box
        pixels[y0:y1, x0:x1] = np.asarray(normal)[y0:y1, x0:x1] * SELECTED_ICON_BRIGHTNESS
    if state in (2, 3):
        x0, x1 = SELECTED_RULE_X
        pixels[SELECTED_RULE_Y, x0:x1] = SELECTED_RULE if state == 2 else SELECTED_HOVER_RULE
    return Image.fromarray(np.clip(np.rint(pixels), 0, 255).astype(np.uint8))


def assemble_button(index, entry):
    stem = Path(entry["file"]).stem
    original = Image.open(ORIGINAL / f"{stem}.jpg").convert("RGB")
    painting = Image.new("RGB", original.size)
    generated = load_painting(SOURCE / f"button{index}-generated.png")
    normal = generated.resize((CELL_WIDTH, CELL_HEIGHT), Image.Resampling.LANCZOS)
    normal = ImageEnhance.Color(normal).enhance(SOURCE_COLOR_STRENGTH)
    mask = np.zeros((original.height, original.width), dtype=np.uint8)
    x0, y0, x1, y1 = LAYOUT["buttons"]["edit_rectangle_xyxy"]
    for state, offset in enumerate(LAYOUT["buttons"]["state_y"]):
        painting.paste(button_state(normal, state, entry["glyph_box"]), (0, offset))
        mask[offset + y0:offset + y1, x0:x1] = 255
    save_asset(stem, original, painting, Image.fromarray(mask))


def main():
    assemble_panel()
    for index, entry in enumerate(LAYOUT["buttons"]["icons"], 1):
        assemble_button(index, entry)
    print("Assembled five native-size masters, editable ORA files and OZJ exports.")


if __name__ == "__main__":
    main()
