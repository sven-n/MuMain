std::optional<int> FindMonsterSoundId(std::string_view name)
{
    const std::optional<ESound> id = Audio::SoundIds::Find(name);
    const ESound* const end = std::end(SoundIdsOfMonsters);
    if (!id || std::find(std::begin(SoundIdsOfMonsters), end, *id) == end)
    {
        return std::nullopt;
    }
    return static_cast<int>(*id);
}
