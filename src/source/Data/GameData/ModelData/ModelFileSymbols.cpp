{
    return MonsterModelSymbols;
}

const ModelFileSymbol* FindModelFileSymbol(std::string_view code)
{
    for (const ModelFileSymbol& symbol : MonsterModelSymbols)
    {
        if (symbol.code == code)
        {
            return &symbol;
        }
    }
    return nullptr;
}
