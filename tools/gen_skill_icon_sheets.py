"""Generate the skill-icon @spritesheets both RmlUi themes use.

Every native skill atlas is a plain grid of 20x28 cells, addressed by (sheet, col, row) -- see
UI::Skills::ResolveIconCell() (src/source/UI/HUD/Skills/SkillIconCell.cpp). RmlUi can't crop an
image by binding an offset (an oversized child is not clipped in this build -- engine-findings.md),
so each cell is a named sprite and C++ binds its name as a decorator. This writes every cell of
every sheet, the same content into each theme, because the icon art is not themed.

Sprite names must match UI::Skills::IconSpriteName():  skill-icon-<sheet>-<col>-<row>

Usage:  python Tools/gen_skill_icon_sheets.py
"""

from pathlib import Path

CELL_W, CELL_H = 20, 28

# (sheet name, source file relative to themes/<theme>/, sheet width, sheet height). Sizes are the
# real frame sizes, not the EXIF thumbnails the .OZJ files also embed.
SHEETS = [
    ("skill1", "../../../newui_skill.jpg", 256, 256),
    ("skill2", "../../../newui_skill2.jpg", 256, 256),
    ("skill3", "../../../newui_skill3.jpg", 256, 256),
    ("command", "../../../newui_command.jpg", 256, 256),
    ("master", "../../../new_Master_Icon.jpg", 512, 512),
]

THEMES = ["legacy", "modern"]

ROOT = Path(__file__).resolve().parent.parent
THEME_DIR = ROOT / "src" / "bin" / "Data" / "Interface" / "RmlUi" / "themes"

HEADER = """/* GENERATED by Tools/gen_skill_icon_sheets.py -- do not edit by hand; rerun the script.

   One named sprite per 20x28 cell of each native skill atlas, addressed the way
   UI::Skills::ResolveIconCell() addresses them. Identical in every theme: the icon art is game data,
   not presentation. */
"""


def render():
    parts = [HEADER]
    for name, src, width, height in SHEETS:
        cols, rows = width // CELL_W, height // CELL_H
        parts.append(f"\n@spritesheet skill-icons-{name}\n{{\n\tsrc: \"{src}\";\n")
        for row in range(rows):
            for col in range(cols):
                parts.append(
                    f"\tskill-icon-{name}-{col}-{row}: {col * CELL_W}px {row * CELL_H}px {CELL_W}px {CELL_H}px;\n"
                )
        parts.append("}\n")
    return "".join(parts)


def main():
    text = render()
    for theme in THEMES:
        out = THEME_DIR / theme / "skill_icons.rcss"
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
