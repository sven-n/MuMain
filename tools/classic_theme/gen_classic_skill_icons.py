"""Generates the classic theme's skill_icons.rcss from the legacy one.

The S6 atlas newui_skill.jpg keeps the 0.97 layout for skills 1-56 (cell (type-1) % 8,
(type-1) / 8, see UI::Skills::Icon::ResolveSkillIcon), so the sprites of those cells
(skill-icon-skill1-{lit,grey}-<column>-<row>, column < 8, row < 7) are moved to a sheet over the
0.97 Interface\\Skill.jpg, whose cells are 32x36. 0.97 has no grey icons: both names use the same
cell. Every other sprite stays as legacy has it.

Usage: python tools/classic_theme/gen_classic_skill_icons.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2] / "src/bin/Data/Interface/RmlUi/themes"
LEGACY = ROOT / "legacy/skill_icons.rcss"
CLASSIC = ROOT / "classic/skill_icons.rcss"

COLUMNS, ROWS, WIDTH, HEIGHT = 8, 7, 32, 36
CLASSIC_SPRITE = re.compile(r"^\s*skill-icon-skill1-(lit|grey)-([0-9]+)-([0-9]+):")


def is_classic_cell(line: str) -> bool:
    match = CLASSIC_SPRITE.match(line)
    return bool(match) and int(match.group(2)) < COLUMNS and int(match.group(3)) < ROWS


def main() -> None:
    legacy = LEGACY.read_text(encoding="utf-8").splitlines()
    body = [line for line in legacy if not is_classic_cell(line)]
    # Drop legacy's header comment; ours explains the file.
    while body and not body[0].startswith("@spritesheet"):
        body.pop(0)

    out = [
        "/* GENERATED by tools/classic_theme/gen_classic_skill_icons.py from ../legacy/skill_icons.rcss -- do not",
        "   edit. Skills 1-56 use the 0.97 icons (../../../Classic/Skill.jpg, 32x36 cells, lit and grey alike);",
        "   everything else is legacy's. */",
        "",
        "@spritesheet skill-icon-classic-sheet",
        "{",
        "\tsrc: ../../../Classic/Skill.jpg;",
    ]
    for state in ("lit", "grey"):
        for row in range(ROWS):
            for column in range(COLUMNS):
                out.append(
                    f"\tskill-icon-skill1-{state}-{column}-{row}: "
                    f"{column * WIDTH}px {row * HEIGHT}px {WIDTH}px {HEIGHT}px;"
                )
    out.append("}")
    out.append("")
    out.extend(body)
    CLASSIC.write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
